/**
 * Regenerates the parts of the docs that are derived from the code that runs:
 * the README's Cypher section, docs/GRAPH-MODEL.md, the parameter reference in
 * docs/tools.md and the repository's llms.txt. A test fails if they drift.
 *   npm run docs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ALL_QUERIES, SCHEMA_INDEXES, type NamedQuery } from '../src/graph/queries.js';
import { MCP_TOOLS } from '../src/mcp/server.js';
import { AGENT_TOOLS, ALL_TOOLS, inputJsonSchema } from '../src/tools/index.js';
import type { ToolDef } from '../src/tools/types.js';
import { llmsTxt, SITE_URL } from '../web/src/docs/manifest.js';

const root = join(import.meta.dirname, '..');
export const START = '<!-- generated:cypher:start -->';
export const END = '<!-- generated:cypher:end -->';

function block(q: NamedQuery): string {
  return `**\`${q.name}\`** — ${q.purpose}\n\n\`\`\`cypher\n${q.cypher}\n\`\`\`\n`;
}

/** The README section: the queries the product depends on (agent tools + memory). */
export function readmeCypher(): string {
  const tools = ALL_TOOLS.map((t) => `| \`${t.name}\` | ${t.queries.map((q) => `\`${q.name}\``).join(', ')} |`).join('\n');
  const groups: [NamedQuery['group'], string][] = [
    ['tool', 'Queries the agent tools run'],
    ['memory', 'Memory: decisions, verdicts, runs, checks'],
  ];
  const parts = [
    START,
    '<!-- Generated by `npm run docs` from src/graph/queries.ts. Do not edit by hand. -->',
    '',
    '| Tool | Cypher it runs |',
    '|---|---|',
    tools,
    '',
  ];
  for (const [g, title] of groups) {
    parts.push(`#### ${title}`, '');
    for (const q of ALL_QUERIES.filter((x) => x.group === g)) parts.push(block(q));
  }
  parts.push(
    `Indexing and reporting queries (${ALL_QUERIES.filter((q) => q.group === 'index' || q.group === 'report').length} more) are in [docs/GRAPH-MODEL.md](docs/GRAPH-MODEL.md).`,
    END,
  );
  return parts.join('\n');
}

export function graphModelDoc(): string {
  const out = [
    '# Graph model',
    '',
    'Generated by `npm run docs` from `src/graph/queries.ts`: every Cypher statement Staleproof sends to FalkorDB, named, with what it is for. One graph per organisation; the graph name is the org slug.',
    '',
    '## Indexes',
    '',
    ...SCHEMA_INDEXES.map(([label, prop]) => `- \`CREATE INDEX FOR (n:${label}) ON (n.${prop})\``),
    '',
  ];
  const groups: [NamedQuery['group'], string][] = [
    ['tool', 'Agent tools'],
    ['memory', 'Memory'],
    ['index', 'Indexing'],
    ['report', 'Reporting'],
  ];
  for (const [g, title] of groups) {
    out.push(`## ${title}`, '');
    for (const q of ALL_QUERIES.filter((x) => x.group === g)) out.push(block(q));
  }
  return out.join('\n');
}

export function replaceGenerated(doc: string, section: string, start = START, end = END): string {
  const a = doc.indexOf(start);
  const b = doc.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`no ${start} … ${end} markers`);
  return doc.slice(0, a) + section + doc.slice(b + end.length);
}

export const TOOLS_START = '<!-- generated:tools:start -->';
export const TOOLS_END = '<!-- generated:tools:end -->';

interface JsonSchema {
  type?: string;
  description?: string;
  enum?: string[];
  items?: JsonSchema;
  minimum?: number;
  maximum?: number;
  minLength?: number;
  minItems?: number;
  properties?: Record<string, JsonSchema>;
  required?: string[];
}

function typeOf(p: JsonSchema): string {
  if (p.enum) return p.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (p.type === 'array') return `${typeOf(p.items ?? {})}[]${p.minItems ? ` (≥ ${p.minItems})` : ''}`;
  if (p.type === 'integer' || p.type === 'number') {
    const max = p.maximum !== undefined && p.maximum < Number.MAX_SAFE_INTEGER ? p.maximum : undefined;
    return `${p.type}${p.minimum !== undefined ? (max !== undefined ? ` ${p.minimum}–${max}` : ` ≥ ${p.minimum}`) : ''}`;
  }
  if (p.type === 'string' && p.minLength && p.minLength > 1) return `string (≥ ${p.minLength} chars)`;
  if (p.type === 'string' && p.minLength === 1) return 'string (non-empty)';
  return p.type ?? 'any';
}

/** Wording for parameters whose schema carries no description of its own. */
const PARAM_HINTS: Record<string, string> = {
  pr_url: 'GitHub pull request URL (`https://github.com/<owner>/<repo>/pull/<n>`)',
  section_id: 'DocSection id (`owner/repo:path#anchor`), as returned by impact',
  new_text: 'Replacement Markdown for the whole section, heading line included',
  reason: 'Why: what the pull request changed and what the section claims',
  cites: 'Decision ids this conclusion relies on',
  runs: 'Run ids (from run_example) that support it',
  text: 'The decision, in one sentence',
  author: 'Who decided',
};

/** The tools graph mode calls, in its fixed order (src/agent/graph-check.ts). */
const GRAPH_MODE_TOOLS = ['impact', 'clearance', 'rank_sections', 'run_example'];

function availability(t: ToolDef): string {
  if (AGENT_TOOLS.includes(t)) return GRAPH_MODE_TOOLS.includes(t.name) ? 'the agent, MCP clients and graph mode' : 'the agent and MCP clients';
  if (t.name === 'write_decision') return 'MCP clients, the CLI (`decide`) and the HTTP API (`POST /api/decisions`); never the agent';
  if (t.name === 'docs_patch') return 'MCP clients; the same patch comes from the CLI (`patch`) and the HTTP API (`GET /api/patch`)';
  return 'MCP clients';
}

/** docs/tools.md: one entry per tool, from the definitions the agent and MCP clients receive. */
export function toolsReference(): string {
  const out = [TOOLS_START, '<!-- Generated by `npm run docs` from src/tools and src/mcp/server.ts. Do not edit by hand. -->', ''];
  for (const t of MCP_TOOLS) {
    const schema = inputJsonSchema(t) as JsonSchema;
    const required = new Set(schema.required ?? []);
    out.push(`### \`${t.name}\``, '', t.description, '', `Available to ${availability(t)}.`, '');
    const props = Object.entries(schema.properties ?? {});
    if (props.length) {
      out.push('| Parameter | Type | Required | Description |', '|---|---|---|---|');
      for (const [name, p] of props) {
        out.push(`| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? 'yes' : 'no'} | ${(p.description ?? PARAM_HINTS[name] ?? '').replace(/\|/g, '\\|')} |`);
      }
      out.push('');
    }
    if (t.queries.length) out.push(`Cypher it runs: ${t.queries.map((q) => `\`${q.name}\``).join(', ')} ([full text](GRAPH-MODEL.md)).`, '');
  }
  out.push(TOOLS_END);
  return out.join('\n');
}

/** The repository's llms.txt: the same index as the site's, linking to the Markdown files on GitHub. */
export function repoLlmsTxt(): string {
  return llmsTxt((d) => `docs/${d.file}`, [
    { title: 'Live demo', url: SITE_URL, summary: 'paste a pull request and watch the check; the docs are also served as Markdown there' },
    { title: 'README', url: 'README.md', summary: 'what it found on FalkorDB’s repositories, why the graph is load-bearing, limits' },
  ]);
}

async function main(): Promise<void> {
  const readmePath = join(root, 'README.md');
  await writeFile(readmePath, replaceGenerated(await readFile(readmePath, 'utf8'), readmeCypher()));
  await writeFile(join(root, 'docs', 'GRAPH-MODEL.md'), `${graphModelDoc()}\n`);
  const toolsPath = join(root, 'docs', 'tools.md');
  await writeFile(toolsPath, replaceGenerated(await readFile(toolsPath, 'utf8'), toolsReference(), TOOLS_START, TOOLS_END));
  await writeFile(join(root, 'llms.txt'), repoLlmsTxt());
  console.log('updated README.md, docs/GRAPH-MODEL.md, docs/tools.md and llms.txt');
}

if (process.argv[1]?.endsWith('gen-docs.ts')) await main();
